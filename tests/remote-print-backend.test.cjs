const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {PGlite}=require('@electric-sql/pglite'),{pgcrypto}=require('@electric-sql/pglite/contrib/pgcrypto');
test('impresión remota: sesiones, elección única, idempotencia, confirmación y caducidad',async()=>{
 const db=new PGlite({extensions:{pgcrypto}});
 try{
  await db.exec(`create role anon;create role authenticated;create schema extensions;create extension pgcrypto with schema extensions;
   create table app_users(id uuid primary key,role text);
   insert into app_users values('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa','boss'),('bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb','admin');
   create function require_app_user(token text) returns app_users language plpgsql as $$declare u app_users;begin
    if token not in ('alice','bob') then raise exception 'No autorizado';end if;
    select * into u from app_users where id=case when token='alice' then 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa' else 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb' end::uuid;return u;end;$$;`);
  const migration=fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261114220000_remote_printing.sql'),'utf8');
  await db.exec(migration);await db.exec(migration);
  const id=n=>`${String(n).padStart(8,'0')}-1111-4111-8111-111111111111`,secret='a'.repeat(43),pdf=Buffer.from('%PDF-1.4\nFake receipt for queue transport').toString('base64');
  const call=async(name,values)=>(await db.query(`select ${name}(${values.map((_,i)=>'$'+(i+1)).join(',')}) result`,values)).rows[0].result;
  const beat=(browser,receiver=null,s=secret)=>call('dp_print_heartbeat',['alice',id(browser),'PC '+browser,receiver?id(receiver):null,receiver?s:null,receiver?'POS 80':null]);
  const submit=(n,token='alice',data=pdf,preferred=null)=>call('dp_print_submit',[token,id(n),'Comanda',data,preferred?id(preferred):null]);
  await assert.rejects(call('dp_print_status',['bad']),/No autorizado/);
  assert.equal((await submit(10)).unavailable,true);
  await beat(1);let status=await call('dp_print_status',['alice']);assert.equal(status.devices,1);assert.equal(status.receivers.length,0);
  await beat(1,100);await beat(2,100);await beat(3,101);
  status=await call('dp_print_status',['alice']);assert.equal(status.devices,3);assert.equal(status.receivers.length,2,'Un PC receptor no se duplica por navegador.');
  await assert.rejects(beat(4,100,'b'.repeat(43)),/Receptor no autorizado/);
  await assert.rejects(submit(10,'bad'),/No autorizado/);
  await assert.rejects(submit(10,'alice','script'),/PDF no válido/);
  const submitted=await submit(10,'alice',pdf,100);assert.equal(submitted.receiver,id(100));
  assert.equal((await submit(10)).id,id(10));
  assert.equal((await db.query('select count(*)::int n from dp_print_jobs')).rows[0].n,1);
  await assert.rejects(submit(10,'bob'),/Identificador/);
  await assert.rejects(submit(10,'alice',pdf+'AAAA'),/Identificador/);
  assert.equal(await call('dp_print_result',['bob',id(10)]),null);
  await assert.rejects(call('dp_print_claim',['alice',id(100),'wrong']),/Receptor no autorizado/);
  assert.equal((await call('dp_print_claim',['alice',id(101),secret])).job,null);
  const claim=()=>call('dp_print_claim',['alice',id(100),secret]);
  assert.equal((await claim()).job.pdf,pdf);assert.equal((await claim()).job.id,id(10),'Un fallo de transporte se reconcilia con el mismo receptor.');
  await assert.rejects(call('dp_print_finish',['alice',id(100),'wrong',id(10),'spooled','']),/Receptor no autorizado/);
  await call('dp_print_finish',['alice',id(100),secret,id(10),'spooled','']);
  assert.equal((await claim()).job,null);assert.equal((await call('dp_print_result',['alice',id(10)])).status,'spooled');
  assert.equal((await db.query('select pdf from dp_print_jobs where id=$1',[id(10)])).rows[0].pdf,null);
  await call('dp_print_finish',['alice',id(100),secret,id(10),'failed','late failure']);
  assert.equal((await call('dp_print_result',['alice',id(10)])).status,'spooled','Una confirmación tardía no sobrescribe un resultado terminal.');
  await submit(11,'alice',pdf,100);await claim();await submit(12,'alice',pdf,100);
  await db.exec("update dp_print_jobs set created_at=now()-interval '3 minutes' where status in ('pending','claimed')");
  await beat(1,100);
  assert.equal((await call('dp_print_result',['alice',id(11)])).status,'unknown');
  assert.equal((await call('dp_print_result',['alice',id(12)])).status,'expired');
  assert.equal((await claim()).job,null,'No se reenvían trabajos antiguos al reconectar.');
  await db.exec("update dp_print_receivers set last_seen=now()-interval '46 seconds'");
  assert.equal((await submit(13)).unavailable,true);
  await db.exec("update dp_print_jobs set finished_at=now()-interval '8 days'");await beat(1);
  assert.equal((await db.query('select count(*)::int n from dp_print_jobs')).rows[0].n,0);
 }finally{await db.close();}
});
